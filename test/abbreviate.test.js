'use strict';

const { test } = require('node:test');
const assert = require('node:assert');
const { abbreviate, RULES } = require('../src/abbreviate');

test('кожне правило зі розкладки працює окремо', () => {
  const expected = {
    'Відокремлений підрозділ': 'ВП',
    'Вище професійне училище': 'ВПУ',
    'Вищий навчальний приватний заклад': 'ВНПЗ',
    'Відокремлений структурний підрозділ': 'ВСП',
    'Відокремлений структурний підрозділ Фаховий коледж': 'ВСПФК',
    'Державний вищий навчальний заклад': 'ДВНЗ',
    'Державний навчальний заклад': 'ДНЗ',
    'Державний професійно-технічний навчальний заклад': 'ДПТНЗ',
    'Комунальний вищий навчальний заклад': 'КВНЗ',
    'Комунальний заклад': 'КЗ',
    'Комунальний заклад вищої освіти': 'КЗВО',
    'Комунальний заклад освіти': 'КЗО',
  };
  for (const [phrase, abbr] of Object.entries(expected)) {
    assert.equal(abbreviate(`${phrase} Тестовий`), `${abbr} Тестовий`, `фраза «${phrase}»`);
  }
});

test('довші фрази скорочуються раніше за коротші', () => {
  // Найважливіше: «Комунальний заклад» не має з'їдати довші варіанти.
  assert.equal(
    abbreviate('Комунальний заклад вищої освіти Дніпровська академія'),
    'КЗВО Дніпровська академія'
  );
  assert.equal(
    abbreviate('Комунальний заклад освіти Покровський коледж'),
    'КЗО Покровський коледж'
  );
  assert.equal(
    abbreviate('Комунальний заклад Львівський коледж'),
    'КЗ Львівський коледж'
  );
  assert.equal(
    abbreviate('Відокремлений структурний підрозділ Фаховий коледж електрифікації'),
    'ВСПФК електрифікації'
  );
  // «Відокремлений структурний підрозділ» не має ставати «Відокремлений ВП»
  assert.equal(
    abbreviate('Відокремлений структурний підрозділ Нікопольський коледж'),
    'ВСП Нікопольський коледж'
  );
  assert.equal(
    abbreviate('Державний професійно-технічний навчальний заклад Криворізький центр'),
    'ДПТНЗ Криворізький центр'
  );
});

test('регістр не має значення — назви приходять і малими літерами', () => {
  assert.equal(
    abbreviate('відокремлений підрозділ фаховий коледж іт степ'),
    'ВП фаховий коледж іт степ'
  );
  assert.equal(
    abbreviate('КОМУНАЛЬНИЙ ЗАКЛАД ВИЩОЇ ОСВІТИ Дніпровська академія'),
    'КЗВО Дніпровська академія'
  );
});

test('подвійні пробіли в назві не ламають заміну', () => {
  assert.equal(
    abbreviate('Державний  навчальний  заклад Малинський професійний ліцей'),
    'ДНЗ Малинський професійний ліцей'
  );
});

test('функція ідемпотентна — повторне скорочення нічого не змінює', () => {
  const once = abbreviate('Відокремлений структурний підрозділ Дубенський коледж');
  assert.equal(abbreviate(once), once);
  assert.equal(abbreviate('ВСП Дубенський коледж'), 'ВСП Дубенський коледж');
});

test('назви без відповідних фраз лишаються незмінними', () => {
  const untouched = 'Білоцерківський національний аграрний університет';
  assert.equal(abbreviate(untouched), untouched);
  assert.equal(abbreviate('Криворізький професійний ліцей'), 'Криворізький професійний ліцей');
});

test('«Вище професійне училище» скорочується в різних відмінках', () => {
  assert.equal(abbreviate('Вище професійне училище №11 м. Вінниці'), 'ВПУ №11 м. Вінниці');
  assert.equal(abbreviate('Вище професійне училища сфери послуг'), 'ВПУ сфери послуг');
});

test('порожні значення не ламають функцію', () => {
  assert.equal(abbreviate(''), '');
  assert.equal(abbreviate(null), '');
  assert.equal(abbreviate(undefined), '');
});

test('розкладка містить усі 12 правил', () => {
  assert.equal(RULES.length, 12);
});

test('abbreviate спрацьовує на NFD-формі тексту (типово для macOS/APFS)', () => {
  // macOS часто повертає літери на кшталт «й», «ї», «є» у розкладеній формі
  // (буква + окремий діакритичний знак) замість зібраної. Без normalize('NFC')
  // усередині abbreviate() жодне правило не знаходило фразу в такому тексті —
  // саме тому на macOS скорочення мовчки не спрацьовувало для будь-якої фрази,
  // що містить такі літери («Комунальний», «Відокремлений» тощо).
  const clean = 'Комунальний заклад освіти Апостолівський центр';
  const nfd = clean.normalize('NFD');
  assert.notEqual(clean, nfd, 'тестові дані мають реально відрізнятися побайтово');
  assert.equal(abbreviate(nfd), abbreviate(clean));
  assert.equal(abbreviate(nfd), 'КЗО Апостолівський центр');
});
