const volume = (ml: number[], indexed = true): Facet => ({
  key: 'volume',
  label: { uk: 'Об’єм', ru: 'Объём' },
  indexed,
  values: ml.map((v) => ({
    value: String(v),
    slug: `${v}-ml`,
    label: { uk: `${v} мл`, ru: `${v} мл` },
  })),
});

const diameter = (mm: number[]): Facet => ({
  key: 'diameter',
  label: { uk: 'Діаметр', ru: 'Диаметр' },
  indexed: true,
  values: mm.map((v) => ({
    value: String(v),
    slug: `${v}-mm`,
    label: { uk: `${v} мм`, ru: `${v} мм` },
  })),
});

const color = (keys: ('kraft' | 'white' | 'black')[], indexed = true): Facet => {
  const dict: Record<string, { slug: string; label: L }> = {
    kraft: { slug: 'kraft', label: { uk: 'Крафт', ru: 'Крафт' } },
    white: { slug: 'bili', label: { uk: 'Білі', ru: 'Белые' } },
    black: { slug: 'chorni', label: { uk: 'Чорні', ru: 'Чёрные' } },
  };
  return {
    key: 'color',
    label: { uk: 'Колір', ru: 'Цвет' },
    indexed,
    values: keys.map((k) => ({ value: k, ...dict[k] })),
  };
};

const custom = (
  key: string,
  label: L,
  values: { value: string; slug: string; label: L }[],
  indexed = false,
): Facet => ({ key, label, values, indexed });

