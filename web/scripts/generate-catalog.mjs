const COLOR_MULT = { kraft: 1.05, white: 1, black: 1.12 };

const products = [];

const add = (p) => {
  const tiers = TIERS.map((t) => ({
    minPacks: t.minPacks,
    perUnit: round(p.priceRetail * (1 - t.discount)),
  }));
  products.push({ ...p, priceRetail: round(p.priceRetail), tiers });
};

