/* ── Сумісність стакан ↔ кришка ────────────────────────────────────── */

const lidsByDiameter = new Map();
for (const p of products) {
  if (p.shape === 'lid') {
    if (!lidsByDiameter.has(p.lidDiameter)) lidsByDiameter.set(p.lidDiameter, []);
    lidsByDiameter.get(p.lidDiameter).push(p.slug);
  }
}
for (const p of products) {
  if (p.shape === 'cup') p.compatibleWith = lidsByDiameter.get(p.lidDiameter) ?? [];
  if (p.shape === 'lid') {
    p.compatibleWith = products
      .filter((c) => c.shape === 'cup' && c.lidDiameter === p.lidDiameter)
      .map((c) => c.slug);
  }
}

/* ── Перевірки цілісності ──────────────────────────────────────────── */

const slugs = new Set();
const skus = new Set();
for (const p of products) {
  if (slugs.has(p.slug)) throw new Error(`Дубль слага: ${p.slug}`);
  if (skus.has(p.sku)) throw new Error(`Дубль артикула: ${p.sku}`);
  slugs.add(p.slug);
  skus.add(p.sku);
}

