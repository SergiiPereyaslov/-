'use strict';

// Порівняння назв замовників — спільне для команд імпорту та звірення.
//
// macOS (APFS) при розпакуванні архівів часто повертає кириличні літери
// на кшталт «ї», «є», «й» у розкладеній формі (буква + окремий
// діакритичний знак, NFD) замість зібраної (один символ, NFC), у якій
// їх зберігає база. Візуально різниці не видно, але без
// normalize('NFC') рядки не збігаються ніколи — саме так на macOS
// жодна папка з договорами не зіставлялася із замовником.
function normalizeName(s) {
  return String(s || '')
    .normalize('NFC')
    .toLowerCase()
    // Невидимі символи, які текст із Word/macOS часто лишає всередині слів
    // (м'який перенос, символи нульової ширини, «з'єднувач слів») — вони
    // не пробіли й не потрапляють під \s, але й на екрані їх не видно.
    .replace(/[­​‌‍⁠]/g, '')
    .replace(/[«»"“”„]/g, ' ')
    .replace(/['’ʼ`´]/g, '')
    // Дефіс/тире: усі поширені варіанти, включно з «м'яким» дефісом U+2010
    // і невідокремлюваним U+2011 — не лише ті три, що трапляються найчастіше.
    .replace(/[‐‑‒–—−-]/g, ' ')
    .replace(/[.,;:()]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

module.exports = { normalizeName };
