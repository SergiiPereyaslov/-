'use strict';

// Скорочення в назвах замовників за розкладкою, узгодженою із замовником.
//
// Порядок у списку критичний: спочатку найдовші фрази, інакше
// «Комунальний заклад вищої освіти» перетворилося б на «КЗ вищої освіти»,
// а «Відокремлений структурний підрозділ Фаховий коледж» — на «ВСП Фаховий коледж».
const RULES = [
  ['Відокремлений структурний підрозділ Фаховий коледж', 'ВСПФК'],
  ['Державний професійно-технічний навчальний заклад', 'ДПТНЗ'],
  ['Вищий навчальний приватний заклад', 'ВНПЗ'],
  ['Відокремлений структурний підрозділ', 'ВСП'],
  ['Комунальний вищий навчальний заклад', 'КВНЗ'],
  ['Державний вищий навчальний заклад', 'ДВНЗ'],
  ['Комунальний заклад вищої освіти', 'КЗВО'],
  ['Комунальний заклад освіти', 'КЗО'],
  ['Державний навчальний заклад', 'ДНЗ'],
  ['Відокремлений підрозділ', 'ВП'],
  // wordTail: остання основа з'їдає закінчення слова, щоб покрити
  // і «училище», і «училища» — інакше лишався б хвіст («ВПУе»).
  ['Вище професійне училищ', 'ВПУ', { wordTail: true }],
  ['Комунальний заклад', 'КЗ'],
];

// Довші фрази — першими (на випадок правок списку вручну).
const ORDERED = [...RULES].sort((a, b) => b[0].length - a[0].length);

function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Пробіл у фразі має відповідати будь-якій кількості пробілів у назві:
// у справжніх назвах трапляються подвійні пробіли.
function phrasePattern(phrase, opts = {}) {
  const base = escapeRegExp(phrase).replace(/\s+/g, '\\s+');
  return opts.wordTail ? `${base}[а-яіїєґ']*` : base;
}

const COMPILED = ORDERED.map(([phrase, abbr, opts]) => ({
  // 'i' — назви приходять у різному регістрі, аж до повністю малих літер.
  re: new RegExp(phrasePattern(phrase, opts), 'gi'),
  abbr,
}));

// Скорочує назву замовника. Якщо скорочення вже стоїть у назві —
// повторно нічого не змінює (функція ідемпотентна).
//
// normalize('NFC') тут критичний, а не косметичний: macOS (APFS) часто
// повертає літери на кшталт «й», «ї», «є» у розкладеній формі (буква +
// окремий діакритичний знак). У такому вигляді жодне правило нижче не
// знаходить фрази в тексті — regex шукає точний, зібраний символ «й»,
// а розкладена форма — це вже два ЗОВСІМ ІНШІ символи. Без цього рядка
// abbreviate() на macOS мовчки нічого не скорочувало.
function abbreviate(name) {
  let out = String(name || '').normalize('NFC');
  for (const { re, abbr } of COMPILED) {
    out = out.replace(re, abbr);
  }
  // Прибираємо подвійні пробіли, що могли лишитися після заміни.
  return out.replace(/\s{2,}/g, ' ').trim();
}

// Які саме правила застосувалися — для звіту перед імпортом.
function appliedRules(name) {
  const src = String(name || '').normalize('NFC');
  return ORDERED.filter(([phrase, , opts]) => new RegExp(phrasePattern(phrase, opts), 'i').test(src))
    .map(([, abbr]) => abbr);
}

module.exports = { abbreviate, appliedRules, RULES };
